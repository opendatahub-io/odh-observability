// Package aigrid contains fixtures and assertion contracts for the AI Grid E2E suite.
package aigrid

import (
	"errors"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

type Backend struct {
	URL       string `yaml:"url"`
	TokenFile string `yaml:"tokenFile"`
	CAFile    string `yaml:"caFile,omitempty"`
}

type GrafanaConfig struct {
	Image       string `yaml:"image"`
	RouteCAFile string `yaml:"routeCAFile,omitempty"`
}

type MaaSConfig struct {
	APIURL         string `yaml:"apiURL"`
	Namespace      string `yaml:"namespace"`
	ModelRef       string `yaml:"modelRef"`
	ModelNamespace string `yaml:"modelNamespace"`
	Username       string `yaml:"username"`
}

type Spoke struct {
	Context        string `yaml:"context"`
	ClusterName    string `yaml:"clusterName"`
	ClusterID      string `yaml:"clusterID"`
	OrganizationID string `yaml:"organizationID"`
	// Subscription is generated by the fixture, never accepted from input YAML.
	Subscription            string     `yaml:"-"`
	MaaS                    MaaSConfig `yaml:"maas"`
	Model                   string     `yaml:"model"`
	ModelLabel              string     `yaml:"modelLabel,omitempty"`
	InferenceURL            string     `yaml:"inferenceURL"`
	CAFile                  string     `yaml:"caFile,omitempty"`
	ControllerNamespace     string     `yaml:"controllerNamespace"`
	ExpectedControllerImage string     `yaml:"expectedControllerImage"`
}

type Config struct {
	HubContext   string        `yaml:"hubContext"`
	Grafana      GrafanaConfig `yaml:"grafana"`
	Metrics      Backend       `yaml:"metrics"`
	Logs         Backend       `yaml:"logs"`
	Spokes       []Spoke       `yaml:"spokes"`
	MetricNameRE string        `yaml:"metricNameRE,omitempty"`
	Timeout      time.Duration `yaml:"timeout,omitempty"`
	PollInterval time.Duration `yaml:"pollInterval,omitempty"`
}

// Load rejects misspelled inputs and resolves file references relative to the config.
// Credentials are supplied as files, never embedded in the YAML or command line.
func Load(filename string) (Config, error) {
	var c Config
	f, err := os.Open(filename)
	if err != nil {
		return c, err
	}
	defer f.Close()
	d := yaml.NewDecoder(f)
	d.KnownFields(true)
	if err := d.Decode(&c); err != nil {
		// YAML decoder errors may quote a supplied credential or URL.
		return c, errors.New("invalid AI Grid configuration YAML (check field names and types)")
	}
	var extra any
	if err := d.Decode(&extra); !errors.Is(err, io.EOF) {
		return c, errors.New("AI Grid configuration must contain exactly one YAML document")
	}
	if c.Timeout == 0 {
		c.Timeout = 5 * time.Minute
	}
	if c.PollInterval == 0 {
		c.PollInterval = 5 * time.Second
	}
	if c.MetricNameRE == "" {
		c.MetricNameRE = "authorized_hits(_total)?"
	}
	base, err := filepath.Abs(filepath.Dir(filename))
	if err != nil {
		return c, err
	}
	resolve := func(p *string) {
		if *p != "" && !filepath.IsAbs(*p) {
			*p = filepath.Join(base, *p)
		}
	}
	for _, b := range []*Backend{&c.Metrics, &c.Logs} {
		resolve(&b.TokenFile)
		resolve(&b.CAFile)
	}
	resolve(&c.Grafana.RouteCAFile)
	for i := range c.Spokes {
		s := &c.Spokes[i]
		if s.ModelLabel == "" {
			s.ModelLabel = s.Model
		}
		resolve(&s.CAFile)
	}
	return c, c.Validate()
}

func (c Config) Validate() error {
	if c.HubContext == "" || c.Grafana.Image == "" {
		return errors.New("hubContext and grafana.image are required")
	}
	if c.Timeout <= 0 || c.Timeout > 30*time.Minute || c.PollInterval <= 0 || c.PollInterval > c.Timeout {
		return errors.New("require 0 < pollInterval <= timeout <= 30m")
	}
	if c.MetricNameRE == "" || len(c.MetricNameRE) > 256 {
		return errors.New("metricNameRE must contain 1 to 256 characters")
	}
	if _, err := regexp.Compile(c.MetricNameRE); err != nil {
		return errors.New("metricNameRE must be a valid RE2 expression")
	}
	for name, b := range map[string]Backend{"metrics": c.Metrics, "logs": c.Logs} {
		if err := validateURL(b.URL); err != nil {
			return fmt.Errorf("%s.url: %w", name, err)
		}
		if b.TokenFile == "" {
			return fmt.Errorf("%s.tokenFile is required", name)
		}
	}
	if strings.Contains(c.Logs.URL, "/otlp") || strings.Contains(c.Logs.URL, "/v1/logs") {
		return errors.New("logs.url must be the Loki query base, not an OTLP ingestion endpoint")
	}
	if len(c.Spokes) != 2 {
		return errors.New("exactly two spokes are required")
	}
	contexts := map[string]bool{c.HubContext: true}
	names, ids := map[string]bool{}, map[string]bool{}
	for i, s := range c.Spokes {
		for field, value := range map[string]string{
			"context": s.Context, "clusterName": s.ClusterName, "clusterID": s.ClusterID,
			"organizationID": s.OrganizationID,
			modelField:       s.Model, "modelLabel": s.ModelLabel,
			"maas.namespace": s.MaaS.Namespace, "maas.modelRef": s.MaaS.ModelRef,
			"maas.modelNamespace": s.MaaS.ModelNamespace, "maas.username": s.MaaS.Username,
			"controllerNamespace": s.ControllerNamespace, "expectedControllerImage": s.ExpectedControllerImage,
		} {
			if strings.TrimSpace(value) == "" {
				return fmt.Errorf("spokes[%d].%s is required", i, field)
			}
		}
		if contexts[s.Context] || names[s.ClusterName] || ids[s.ClusterID] {
			return errors.New("hub/spoke contexts and spoke source cluster identities must be distinct")
		}
		contexts[s.Context], names[s.ClusterName], ids[s.ClusterID] = true, true, true
		if !regexp.MustCompile(`@sha256:[a-f0-9]{64}$`).MatchString(s.ExpectedControllerImage) {
			return fmt.Errorf("spokes[%d].expectedControllerImage must be pinned by sha256 digest", i)
		}
		if err := validateURL(s.InferenceURL); err != nil {
			return fmt.Errorf("spokes[%d].inferenceURL: %w", i, err)
		}
		if err := validateURL(s.MaaS.APIURL); err != nil {
			return fmt.Errorf("spokes[%d].maas.apiURL: %w", i, err)
		}
	}
	return nil
}

func validateURL(raw string) error {
	u, err := url.Parse(raw)
	if err != nil || u.Scheme != "https" || u.Hostname() == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return errors.New("require an HTTPS URL without credentials, query parameters or a fragment")
	}
	return nil
}

func ReadCredential(filename string) (string, error) {
	b, err := os.ReadFile(filename)
	if err != nil {
		return "", err
	}
	s := strings.TrimSpace(string(b))
	if s == "" || strings.ContainsAny(s, "\r\n") {
		return "", errors.New("credential file must contain one nonempty token")
	}
	return s, nil
}
